        <div class="mb-4">
          <h5 class="fw-bold text-dark mb-1">2. Record Monthly Primary Salary (Income)</h5>
          <p class="small text-muted mb-1">At the start of each month, navigate to <strong>Income</strong> and record your base salary (e.g., ₦500,000). Dynamic percentage categories automatically compute their budget targets.</p>
        </div>

        <div class="mb-4">
          <h5 class="fw-bold text-dark mb-1">3. Track Actual Spending (Tracker)</h5>
