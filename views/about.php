        <div class="mb-4">
          <h5 class="fw-bold text-dark mb-1">1. Set Up Budget Categories (Settings)</h5>
          <p class="small text-muted mb-1">Define fixed monthly commitments (e.g., Foodstuff ₦45,000, Rent Savings ₦45,000) or dynamic percentages of salary (e.g., Investment 5%, Emergency Fund 10%).</p>
